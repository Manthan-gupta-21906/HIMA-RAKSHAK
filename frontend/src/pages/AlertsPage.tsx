import { useCallback, useEffect, useState } from "react";
import {
  acknowledgeAlert,
  fetchAlerts,
  updateAlertAction,
  type AlertHazardType,
  type AlertRecord,
  type AlertStatus,
} from "../api/alerts";
import { fetchLocations } from "../api/locations";
import { Badge, type BadgeTone } from "../components/ui/Badge";
import { useAuth } from "../context/AuthContext";

type StatusFilter = "all" | AlertStatus;
type HazardFilter = "all" | AlertHazardType;

const STATUS_LABEL: Record<AlertStatus, string> = {
  active: "Active",
  acknowledged: "Acknowledged",
  in_progress: "In Progress",
  resolved: "Resolved",
};

const STATUS_TONE: Record<AlertStatus, BadgeTone> = {
  active: "emergency",
  acknowledged: "warning",
  in_progress: "cwc",
  resolved: "clear",
};

const PRIORITY_TONE: Record<string, BadgeTone> = {
  CRITICAL: "emergency",
  HIGH: "warning",
  MEDIUM: "neutral",
  LOW: "clear",
};

function formatTimestamp(value: string | null): string {
  if (!value) return "—";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  return date.toLocaleString([], { dateStyle: "medium", timeStyle: "short" });
}

/**
 * Operational alerts generated by the risk workflow.
 *
 * Deliberately distinct from authoritative `/warnings` bulletins: alerts are
 * system recommendations that operators can acknowledge and action. There is
 * no mock fallback — if the backend feed is unavailable the page says so.
 */
export function AlertsPage() {
  const { user } = useAuth();
  const canAct = user?.role === "admin" || user?.role === "district_operator";

  const [alerts, setAlerts] = useState<AlertRecord[]>([]);
  const [locationNames, setLocationNames] = useState<Record<string, string>>({});
  const [statusFilter, setStatusFilter] = useState<StatusFilter>("all");
  const [hazardFilter, setHazardFilter] = useState<HazardFilter>("all");
  const [selectedId, setSelectedId] = useState("");
  const [isLoading, setIsLoading] = useState(true);
  const [isLive, setIsLive] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const [ackNote, setAckNote] = useState("");
  const [actionStatus, setActionStatus] = useState<AlertStatus>("active");
  const [actionNote, setActionNote] = useState("");
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [submitError, setSubmitError] = useState<string | null>(null);
  const [submitMessage, setSubmitMessage] = useState<string | null>(null);

  const loadAlerts = useCallback(async () => {
    setIsLoading(true);
    setError(null);
    try {
      const response = await fetchAlerts({
        status: statusFilter === "all" ? undefined : statusFilter,
        hazard_type: hazardFilter === "all" ? undefined : hazardFilter,
      });
      setAlerts(response.items);
      setIsLive(true);
      setSelectedId((prev) =>
        response.items.some((alert) => alert.alert_id === prev)
          ? prev
          : (response.items[0]?.alert_id ?? "")
      );
    } catch (err) {
      setAlerts([]);
      setIsLive(false);
      setError(
        err instanceof Error ? err.message : "Unable to load operational alerts."
      );
    } finally {
      setIsLoading(false);
    }
  }, [statusFilter, hazardFilter]);

  useEffect(() => {
    void loadAlerts();
  }, [loadAlerts]);

  useEffect(() => {
    let isMounted = true;
    fetchLocations({ page_size: 100 })
      .then((response) => {
        if (!isMounted) return;
        setLocationNames(
          Object.fromEntries(response.items.map((loc) => [loc.location_id, loc.name]))
        );
      })
      .catch(() => {
        // Location names are a convenience; the alert still renders with its ID.
      });
    return () => {
      isMounted = false;
    };
  }, []);

  const selectedAlert =
    alerts.find((alert) => alert.alert_id === selectedId) ?? alerts[0] ?? null;

  useEffect(() => {
    if (!selectedAlert) return;
    setActionStatus(selectedAlert.status);
    setActionNote(selectedAlert.action_note ?? "");
    setAckNote("");
    setSubmitError(null);
    setSubmitMessage(null);
    // Reset the action form only when the operator selects a different alert.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [selectedAlert?.alert_id]);

  const handleAcknowledge = async () => {
    if (!selectedAlert) return;
    setIsSubmitting(true);
    setSubmitError(null);
    setSubmitMessage(null);
    try {
      await acknowledgeAlert(selectedAlert.alert_id, ackNote.trim() || undefined);
      setAckNote("");
      setSubmitMessage("Alert acknowledged.");
      await loadAlerts();
    } catch (err) {
      setSubmitError(err instanceof Error ? err.message : "Could not acknowledge alert.");
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleActionUpdate = async () => {
    if (!selectedAlert) return;
    setIsSubmitting(true);
    setSubmitError(null);
    setSubmitMessage(null);
    try {
      await updateAlertAction(
        selectedAlert.alert_id,
        actionStatus,
        actionNote.trim() || undefined
      );
      setSubmitMessage("Action status updated.");
      await loadAlerts();
    } catch (err) {
      setSubmitError(err instanceof Error ? err.message : "Could not update action status.");
    } finally {
      setIsSubmitting(false);
    }
  };

  const counts = {
    active: alerts.filter((alert) => alert.status === "active").length,
    acknowledged: alerts.filter((alert) => alert.status === "acknowledged").length,
    in_progress: alerts.filter((alert) => alert.status === "in_progress").length,
    resolved: alerts.filter((alert) => alert.status === "resolved").length,
  };

  return (
    <div className="flex flex-col gap-5">
      <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-4 pb-4 border-b border-border-hairline">
        <div>
          <div className="flex flex-wrap items-center gap-2">
            <span className="text-[10px] font-bold uppercase tracking-[0.08em] text-text-muted">
              System-Generated Operational Alerts
            </span>
            <Badge tone={isLive ? "clear" : error ? "emergency" : "neutral"}>
              {isLive ? "Live Backend Feed" : error ? "Feed Unavailable" : "Connecting…"}
            </Badge>
            <Badge tone="neutral">Not Official Warnings</Badge>
          </div>
          <h1 className="text-2xl font-bold text-text-primary tracking-tight mt-0.5">
            Operational Alerts
          </h1>
          <p className="text-xs sm:text-sm text-secondary mt-0.5">
            Risk-workflow recommendations for operator action. Authoritative IMD,
            CWC, and DGRE bulletins remain read-only under Official Warnings.
          </p>
        </div>

        <button
          type="button"
          onClick={() => void loadAlerts()}
          disabled={isLoading}
          className="inline-flex items-center gap-1.5 px-4 py-2 rounded-full bg-surface-container hover:bg-surface-container-high text-text-primary text-xs font-semibold transition-colors cursor-pointer disabled:opacity-60 self-start lg:self-auto"
        >
          <span className={`material-symbols-outlined text-[16px] ${isLoading ? "animate-spin" : ""}`}>
            refresh
          </span>
          <span>Refresh Alerts</span>
        </button>
      </div>

      <section aria-label="Alert summary" className="grid grid-cols-2 lg:grid-cols-4 gap-4">
        {(
          [
            ["Active", counts.active],
            ["Acknowledged", counts.acknowledged],
            ["In Progress", counts.in_progress],
            ["Resolved", counts.resolved],
          ] as const
        ).map(([label, value]) => (
          <div
            key={label}
            className="p-4 rounded-xl bg-surface-card border border-border-hairline flex flex-col gap-1"
          >
            <span className="text-[10px] font-bold text-text-muted uppercase tracking-[0.08em]">
              {label}
            </span>
            <span className="text-xl font-bold text-text-primary">{value}</span>
            <span className="text-[11px] text-secondary">
              {isLive ? "Backend alert table" : "Awaiting backend feed"}
            </span>
          </div>
        ))}
      </section>

      {error && (
        <div
          role="alert"
          className="px-4 py-3 rounded-xl bg-amber-500/10 border border-amber-500/30 text-xs text-amber-900 dark:text-amber-200 flex flex-wrap items-center justify-between gap-3"
        >
          <div className="flex items-center gap-2">
            <span className="material-symbols-outlined text-[18px] text-amber-500">wifi_off</span>
            <span>Backend /alerts API unavailable: {error}</span>
          </div>
          <button
            type="button"
            onClick={() => void loadAlerts()}
            className="px-3 py-1 rounded bg-surface-container hover:bg-surface-container-high text-text-primary font-semibold"
          >
            Retry Connection
          </button>
        </div>
      )}

      <section
        aria-label="Alert filters"
        className="bg-surface-card border border-border-hairline rounded-xl p-4 flex flex-wrap items-center justify-between gap-3"
      >
        <div className="flex flex-wrap items-center gap-2">
          {(["all", "active", "acknowledged", "in_progress", "resolved"] as const).map(
            (status) => (
              <button
                key={status}
                type="button"
                onClick={() => setStatusFilter(status)}
                className={`px-3.5 py-1.5 rounded-full text-xs font-semibold transition-colors cursor-pointer ${
                  statusFilter === status
                    ? "bg-primary-container text-on-primary"
                    : "bg-surface-container text-on-surface-variant hover:bg-surface-container-high"
                }`}
              >
                {status === "all" ? "All Statuses" : STATUS_LABEL[status]}
              </button>
            )
          )}
        </div>

        <select
          aria-label="Filter alerts by hazard"
          value={hazardFilter}
          onChange={(event) => setHazardFilter(event.target.value as HazardFilter)}
          className="h-8 px-3 rounded-full bg-surface-container-low border border-border-hairline text-xs font-semibold text-text-primary"
        >
          <option value="all">All Hazards</option>
          <option value="flood">Flood</option>
          <option value="avalanche">Avalanche</option>
        </select>
      </section>

      {isLoading ? (
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-5">
          <div className="lg:col-span-7 flex flex-col gap-3">
            {[1, 2, 3].map((slot) => (
              <div
                key={slot}
                className="bg-surface-card border border-border-hairline rounded-xl p-5 h-32 animate-pulse"
              />
            ))}
          </div>
          <div className="lg:col-span-5 bg-surface-card border border-border-hairline rounded-xl p-5 h-80 animate-pulse" />
        </div>
      ) : alerts.length === 0 ? (
        <div className="bg-surface-card border border-border-hairline rounded-xl p-8 text-center text-xs text-text-muted">
          {error
            ? "No alerts can be displayed until the backend feed is reachable."
            : "No operational alerts match the current filters."}
        </div>
      ) : (
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-5 items-start">
          <div className="lg:col-span-7 flex flex-col gap-3">
            {alerts.map((alert) => {
              const isSelected = selectedAlert?.alert_id === alert.alert_id;
              return (
                <button
                  key={alert.alert_id}
                  type="button"
                  onClick={() => setSelectedId(alert.alert_id)}
                  className={`w-full text-left bg-surface-card rounded-xl p-5 border transition-all cursor-pointer flex flex-col gap-2.5 ${
                    isSelected
                      ? "border-primary-container shadow-sm"
                      : "border-border-hairline hover:bg-surface-container-low/50"
                  }`}
                >
                  <div className="flex flex-wrap items-center justify-between gap-2">
                    <div className="flex flex-wrap items-center gap-2">
                      <Badge tone={PRIORITY_TONE[alert.priority_level] ?? "neutral"}>
                        {alert.priority_level}
                      </Badge>
                      <Badge tone={STATUS_TONE[alert.status]}>{STATUS_LABEL[alert.status]}</Badge>
                      <span className="text-[11px] font-semibold text-text-muted capitalize">
                        {alert.hazard_type}
                      </span>
                    </div>
                    <span className="text-[11px] text-text-muted">
                      {formatTimestamp(alert.created_at)}
                    </span>
                  </div>

                  <h2 className="text-sm sm:text-base font-bold text-text-primary">{alert.title}</h2>
                  <p className="text-xs text-secondary line-clamp-2">{alert.recommendation}</p>

                  <div className="flex flex-wrap items-center justify-between gap-2 pt-2 border-t border-border-hairline text-[11px] text-text-muted">
                    <span>
                      {locationNames[alert.location_id] ?? alert.location_id}
                    </span>
                    <span>Priority score: {(alert.priority_score * 100).toFixed(0)}%</span>
                  </div>
                </button>
              );
            })}
          </div>

          <aside className="lg:col-span-5">
            {selectedAlert ? (
              <section
                aria-labelledby="alert-detail-title"
                className="bg-surface-card rounded-xl border border-border-hairline shadow-xs p-5 flex flex-col gap-4"
              >
                <div className="flex flex-col gap-2 pb-3 border-b border-border-hairline">
                  <div className="flex flex-wrap items-center gap-1.5">
                    <Badge tone={PRIORITY_TONE[selectedAlert.priority_level] ?? "neutral"}>
                      {selectedAlert.priority_level}
                    </Badge>
                    <Badge tone={STATUS_TONE[selectedAlert.status]}>
                      {STATUS_LABEL[selectedAlert.status]}
                    </Badge>
                    <Badge tone="neutral">System Alert</Badge>
                  </div>
                  <h2
                    id="alert-detail-title"
                    className="text-base font-bold text-text-primary"
                  >
                    {selectedAlert.title}
                  </h2>
                  <p className="text-[11px] text-text-muted">
                    {selectedAlert.alert_id} •{" "}
                    {locationNames[selectedAlert.location_id] ?? selectedAlert.location_id}
                  </p>
                </div>

                <dl className="grid grid-cols-2 gap-2 text-xs">
                  <div className="rounded-lg bg-surface-container-low border border-border-hairline p-2.5">
                    <dt className="text-[10px] font-bold uppercase tracking-wider text-text-muted">
                      Hazard
                    </dt>
                    <dd className="font-semibold text-text-primary mt-0.5 capitalize">
                      {selectedAlert.hazard_type}
                    </dd>
                  </div>
                  <div className="rounded-lg bg-surface-container-low border border-border-hairline p-2.5">
                    <dt className="text-[10px] font-bold uppercase tracking-wider text-text-muted">
                      Priority Score
                    </dt>
                    <dd className="font-semibold text-text-primary mt-0.5">
                      {(selectedAlert.priority_score * 100).toFixed(0)}%
                    </dd>
                  </div>
                  <div className="col-span-2 rounded-lg bg-surface-container-low border border-border-hairline p-2.5">
                    <dt className="text-[10px] font-bold uppercase tracking-wider text-text-muted">
                      Created
                    </dt>
                    <dd className="font-semibold text-text-primary mt-0.5">
                      {formatTimestamp(selectedAlert.created_at)}
                    </dd>
                  </div>
                </dl>

                <div>
                  <span className="text-[10px] font-bold uppercase tracking-wider text-text-muted">
                    Recommended Action
                  </span>
                  <p className="text-xs text-on-surface-variant mt-1.5">
                    {selectedAlert.recommendation}
                  </p>
                </div>

                <div>
                  <span className="text-[10px] font-bold uppercase tracking-wider text-text-muted">
                    Explanation
                  </span>
                  <ul className="mt-1.5 flex flex-col gap-1.5">
                    {selectedAlert.explanation.length === 0 ? (
                      <li className="text-[11px] text-text-muted">
                        No explanation was recorded for this alert.
                      </li>
                    ) : (
                      selectedAlert.explanation.map((line) => (
                        <li
                          key={line}
                          className="flex items-start gap-1.5 text-[11px] text-on-surface-variant"
                        >
                          <span className="material-symbols-outlined text-[14px] text-text-muted shrink-0">
                            chevron_right
                          </span>
                          <span>{line}</span>
                        </li>
                      ))
                    )}
                  </ul>
                </div>

                <div className="pt-3 border-t border-border-hairline flex flex-col gap-1 text-[11px]">
                  <div className="flex justify-between gap-2">
                    <span className="text-text-muted">Acknowledged by</span>
                    <span className="font-semibold text-text-primary">
                      {selectedAlert.acknowledged_by ?? "Not acknowledged"}
                    </span>
                  </div>
                  <div className="flex justify-between gap-2">
                    <span className="text-text-muted">Acknowledged at</span>
                    <span className="font-medium text-on-surface-variant">
                      {formatTimestamp(selectedAlert.acknowledged_at)}
                    </span>
                  </div>
                  <div className="flex justify-between gap-2">
                    <span className="text-text-muted">Action updated</span>
                    <span className="font-medium text-on-surface-variant">
                      {formatTimestamp(selectedAlert.action_updated_at)}
                    </span>
                  </div>
                  <div className="flex justify-between gap-2">
                    <span className="text-text-muted">Action note</span>
                    <span className="font-medium text-on-surface-variant text-right">
                      {selectedAlert.action_note ?? "—"}
                    </span>
                  </div>
                </div>

                {canAct ? (
                  <div className="pt-3 border-t border-border-hairline flex flex-col gap-3">
                    <div className="flex flex-col gap-1.5">
                      <label
                        htmlFor="alert-ack-note"
                        className="text-[10px] font-bold uppercase tracking-wider text-text-muted"
                      >
                        Acknowledge Note (optional)
                      </label>
                      <textarea
                        id="alert-ack-note"
                        value={ackNote}
                        onChange={(event) => setAckNote(event.target.value)}
                        maxLength={500}
                        rows={2}
                        placeholder="Reason for acknowledgement…"
                        className="w-full rounded-lg bg-surface-container-lowest border border-border-hairline p-2.5 text-xs text-text-primary focus:outline-none focus:border-primary-container"
                      />
                      <button
                        type="button"
                        onClick={() => void handleAcknowledge()}
                        disabled={isSubmitting}
                        className="self-start inline-flex items-center gap-1.5 h-8 px-3.5 rounded-full bg-primary-container text-on-primary text-[11px] font-semibold disabled:opacity-60 cursor-pointer"
                      >
                        <span className="material-symbols-outlined text-[15px]">task_alt</span>
                        Acknowledge Alert
                      </button>
                    </div>

                    <div className="flex flex-col gap-1.5">
                      <label
                        htmlFor="alert-action-status"
                        className="text-[10px] font-bold uppercase tracking-wider text-text-muted"
                      >
                        Action Status
                      </label>
                      <select
                        id="alert-action-status"
                        value={actionStatus}
                        onChange={(event) => setActionStatus(event.target.value as AlertStatus)}
                        className="h-9 px-3 rounded-lg bg-surface-container-lowest border border-border-hairline text-xs font-semibold text-text-primary"
                      >
                        <option value="active">Active</option>
                        <option value="acknowledged">Acknowledged</option>
                        <option value="in_progress">In Progress</option>
                        <option value="resolved">Resolved</option>
                      </select>
                      <textarea
                        id="alert-action-note"
                        aria-label="Action note"
                        value={actionNote}
                        onChange={(event) => setActionNote(event.target.value)}
                        maxLength={500}
                        rows={2}
                        placeholder="Action taken or current status note…"
                        className="w-full rounded-lg bg-surface-container-lowest border border-border-hairline p-2.5 text-xs text-text-primary focus:outline-none focus:border-primary-container"
                      />
                      <button
                        type="button"
                        onClick={() => void handleActionUpdate()}
                        disabled={isSubmitting}
                        className="self-start inline-flex items-center gap-1.5 h-8 px-3.5 rounded-full bg-surface-container hover:bg-surface-container-high text-text-primary text-[11px] font-semibold disabled:opacity-60 cursor-pointer"
                      >
                        <span className="material-symbols-outlined text-[15px]">save</span>
                        Save Action Update
                      </button>
                    </div>

                    {submitError && (
                      <p role="alert" className="text-[11px] font-medium text-emergency-red">
                        {submitError}
                      </p>
                    )}
                    {submitMessage && (
                      <p role="status" className="text-[11px] font-medium text-alert-green">
                        {submitMessage}
                      </p>
                    )}
                  </div>
                ) : (
                  <div className="pt-3 border-t border-border-hairline text-[11px] text-text-muted flex items-center gap-2">
                    <span className="material-symbols-outlined text-[15px]">lock</span>
                    Read-only: operator or administrator role required to acknowledge or
                    action this alert.
                  </div>
                )}
              </section>
            ) : null}
          </aside>
        </div>
      )}
    </div>
  );
}
